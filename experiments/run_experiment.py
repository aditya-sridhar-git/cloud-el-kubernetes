"""Run one scaling experiment against an app deployed on the platform.

1. Apply a configuration to the app through the platform API:
     baseline     naive defaults (100m/128Mi requests, HPA 1-10 at 50% CPU)
     recommended  the latest recommendation generated by the platform
     current      leave the app as it is
2. Wait until the rollout succeeded and the app has cooled down to its minimum replicas.
3. Run Locust headless with the chosen load scenario.
4. Save Locust CSVs, the platform's metric samples and run metadata to results/<run>/.

Example (PowerShell):
  python run_experiment.py --platform http://platform.<ip>.nip.io --token <API token> `
      --app flask-app --config baseline --scenario step
"""
import argparse
import json
import os
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

import requests

HERE = Path(__file__).parent
BASELINE = {
    "cpu_request_m": 100,
    "cpu_limit_m": 500,
    "mem_request_mi": 128,
    "mem_limit_mi": 256,
    "hpa_min": 1,
    "hpa_max": 10,
    "hpa_cpu_target": 50,
}
CONFIG_FIELDS = list(BASELINE)


class Platform:
    def __init__(self, base: str, token: str) -> None:
        self.base = base.rstrip("/") + "/api"
        self.s = requests.Session()
        self.s.headers["Authorization"] = f"Bearer {token}"

    def call(self, method: str, path: str, **kw):
        r = self.s.request(method, self.base + path, timeout=30, **kw)
        if not r.ok:
            sys.exit(f"{method} {path} failed: {r.status_code} {r.text}")
        return r.json() if r.content else None


def apply_config(p: Platform, app: str, config: str) -> dict:
    if config == "current":
        return {k: p.call("GET", f"/apps/{app}")[k] for k in CONFIG_FIELDS}
    if config == "baseline":
        values = BASELINE
    else:
        recs = [r for r in p.call("GET", f"/apps/{app}/recommendations") if r["status"] != "dismissed"]
        if not recs:
            sys.exit("no recommendation found: run a training load, then generate one in the dashboard (Scaling tab)")
        values = {k: recs[0]["payload"][k] for k in CONFIG_FIELDS}
        print(f"using recommendation #{recs[0]['id']}")

    result = p.call("PATCH", f"/apps/{app}", json=values)
    if result["deployment"]:
        wait_for_deployment(p, app, result["deployment"]["id"])
    return values


def wait_for_deployment(p: Platform, app: str, dep_id: int, timeout: int = 600) -> None:
    deadline = time.time() + timeout
    while time.time() < deadline:
        dep = next(d for d in p.call("GET", f"/apps/{app}/deployments") if d["id"] == dep_id)
        if dep["status"] == "SUCCEEDED":
            print(f"deployment #{dep_id} succeeded")
            return
        if dep["status"] in ("FAILED", "ROLLED_BACK"):
            sys.exit(f"deployment #{dep_id} {dep['status']}: {dep['error']}")
        time.sleep(5)
    sys.exit(f"deployment #{dep_id} did not finish in {timeout}s")


def wait_for_cooldown(p: Platform, app: str, timeout: int = 600) -> None:
    """Start every run from the same state: minimum replicas, all ready."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        st = p.call("GET", f"/apps/{app}/status")
        dep, hpa = st["deployment"], st["hpa"]
        if dep and hpa and dep["desired"] == hpa["min"] and dep["ready"] == dep["desired"]:
            print(f"cooled down to {dep['ready']} replica(s)")
            return
        print(f"waiting for scale-down: {dep['ready'] if dep else '?'} ready, min {hpa['min'] if hpa else '?'}")
        time.sleep(15)
    print("warning: app did not return to minReplicas; starting anyway")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--platform", required=True, help="e.g. http://platform.<ip>.nip.io")
    ap.add_argument("--token", default=os.getenv("PLATFORM_TOKEN"), help="API token (or PLATFORM_TOKEN env var)")
    ap.add_argument("--app", required=True)
    ap.add_argument("--config", choices=["baseline", "recommended", "current"], default="current")
    ap.add_argument("--scenario", choices=["step", "spike", "periodic"], default="step")
    ap.add_argument("--peak-users", type=int, default=40)
    ap.add_argument("--work-ms", type=int, default=50, help="CPU time per request on the server")
    ap.add_argument("--label", default="", help="optional suffix for the run folder, e.g. run1")
    args = ap.parse_args()
    if not args.token:
        sys.exit("--token or PLATFORM_TOKEN is required")

    p = Platform(args.platform, args.token)
    app = p.call("GET", f"/apps/{args.app}")
    values = apply_config(p, args.app, args.config)
    wait_for_cooldown(p, args.app)

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    run_dir = HERE / "results" / "-".join(filter(None, [args.scenario, args.config, stamp, args.label]))
    run_dir.mkdir(parents=True)

    env = {**os.environ, "SCENARIO": args.scenario, "PEAK_USERS": str(args.peak_users), "WORK_MS": str(args.work_ms)}
    cmd = [
        sys.executable, "-m", "locust", "-f", str(HERE / "locustfile.py"), "--headless",
        "--host", app["url"], "--csv", str(run_dir / "locust"), "--csv-full-history", "--only-summary",
    ]
    print(f"running {args.scenario} load against {app['url']} ...")
    t_start = time.time()
    subprocess.run(cmd, env=env, check=False)
    t_end = time.time()

    # Let the final samples (and the scale-down) land before collecting.
    time.sleep(30)
    samples = p.call("GET", f"/apps/{args.app}/metrics", params={"since": t_start - 30, "until": t_end + 30})
    (run_dir / "metrics.json").write_text(json.dumps(samples, indent=1))
    (run_dir / "meta.json").write_text(
        json.dumps(
            {
                "app": args.app,
                "config": args.config,
                "scenario": args.scenario,
                "peak_users": args.peak_users,
                "work_ms": args.work_ms,
                "settings": values,
                "t_start": t_start,
                "t_end": t_end,
            },
            indent=1,
        )
    )
    print(f"results saved to {run_dir}")


if __name__ == "__main__":
    main()
